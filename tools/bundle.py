#!/usr/bin/env python3
"""
Aurora UI — single-file bundler.

Flattens the Rojo module tree into one paste-and-run Luau file for
environments with no ModuleScripts (mobile executors, loadstring, etc.).

    python3 tools/bundle.py

Emits:
    dist/AuroraUI.luau       <- library only  (returns the Aurora table)
    dist/AuroraDemo.luau     <- library + demo, runs immediately
    dist/AuroraPreview.luau  <- library + live preview, runs immediately
"""

import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LIB = os.path.join(ROOT, "src", "UI", "UILibrary")
DIST = os.path.join(ROOT, "dist")

ORDER = [
    "Theme", "Util", "Icons", "Styles",
    "Row", "Button", "Toggle", "Slider", "Dropdown", "TextBox",
    "Keybind", "ColorPicker", "Section", "Notification", "Tooltip",
    "StatCard", "Tab", "Window", "init", "Preview",
]

# Modules that live in the library root instead of Components/
ROOT_MODULES = ("Theme", "Util", "Icons", "Styles", "init", "Preview")

HEADER = """--[[
	Aurora UI {version} — single-file build
	==================================================================
	Generated by tools/bundle.py from the Rojo module tree.

	Paste this entire file into your script editor and execute it.
	It returns the library table:

		local Aurora = <this file>
		local window = Aurora.CreateWindow({{ Title = "Aurora" }})
		local tab    = window:CreateTab({{ Name = "Home", Icon = "home" }})
		tab:CreateSection({{ Name = "Combat", Icon = "shield" }})
			:AddToggle({{ Name = "Example", Default = true, Callback = print }})

	The window starts open, is draggable/resizable, scales itself down to
	fit small screens, and on touch devices adds a floating reopen button
	(there is no RightShift on a phone).

	No ModuleScripts, no asset ids, no external calls.
--]]

"""

# Injected at the top of every build: tiny shims for executors/older
# Luau runtimes that ship without `task` or `math.clamp`.
COMPAT = """-- Compatibility shims -------------------------------------------------
if not task then
	task = {}
	task.wait = wait or function() end
	task.spawn = spawn or function(fn, ...) return fn(...) end
	task.delay = delay or function(_, fn, ...) return fn(...) end
	task.defer = function(fn, ...) return fn(...) end
	task.cancel = function() end
end

if not math.clamp then
	function math.clamp(value, minimum, maximum)
		return math.min(math.max(value, minimum), maximum)
	end
end

if not table.clone then
	function table.clone(source)
		local copy = {}
		for key, value in pairs(source) do
			copy[key] = value
		end
		return copy
	end
end

if not table.pack then
	function table.pack(...)
		return { n = select("#", ...), ... }
	end
end
----------------------------------------------------------------------

"""

MODULE_TEMPLATE = 'Modules["{name}"] = function()\n{body}\nend\n'

REQUIRE_PATTERN = re.compile(r"require\(\s*script(?:\.[A-Za-z_][A-Za-z0-9_]*)*\s*\)")


def read(name):
    filename = "init.luau" if name == "init" else f"{name}.luau"
    path = os.path.join(LIB, filename) if name in ROOT_MODULES \
        else os.path.join(LIB, "Components", filename)
    with open(path, "r", encoding="utf-8") as handle:
        return handle.read()


def transform(body, known):
    resolved = []

    def replace(match):
        segments = match.group(0)
        inner = segments[segments.index("script") : segments.rindex(")")]
        target = inner.split(".")[-1]
        if target not in known:
            raise SystemExit(f"[bundle] unresolved require target: {target}")
        resolved.append(target)
        return f'__req("{target}")'

    body = REQUIRE_PATTERN.sub(replace, body)
    return body, resolved


def source_version():
    with open(os.path.join(LIB, "Util.luau"), "r", encoding="utf-8") as handle:
        match = re.search(r'Util\.Version\s*=\s*"([^"]+)"', handle.read())
    if not match:
        raise SystemExit("[bundle] could not read Util.Version")
    return match.group(1)


def build_core(entry="init"):
    """Flatten every module reachable from `entry` into one IIFE."""
    version = source_version()
    known = set(ORDER)
    sources = {name: read(name) for name in ORDER}

    # Static dependency scan ------------------------------------------
    dependencies = {}
    for name, body in sources.items():
        found = set()
        for match in REQUIRE_PATTERN.finditer(body):
            segments = match.group(0)
            inner = segments[segments.index("script") : segments.rindex(")")]
            target = inner.split(".")[-1]
            if target not in known:
                raise SystemExit(f"[bundle] unresolved require target: {target}")
            found.add(target)
        dependencies[name] = found

    # Cycle check -----------------------------------------------------
    state = {}

    def visit(node, stack):
        if state.get(node) == "done":
            return
        if state.get(node) == "visiting":
            raise SystemExit("[bundle] circular require: " + " -> ".join(stack + [node]))
        state[node] = "visiting"
        for dep in sorted(dependencies.get(node, ())):
            visit(dep, stack + [node])
        state[node] = "done"

    for name in ORDER:
        visit(name, [])

    # Only ship what the entry point can actually reach ----------------
    reachable = set()

    def mark(node):
        if node in reachable:
            return
        reachable.add(node)
        for dep in dependencies.get(node, ()):
            mark(dep)

    mark(entry)

    modules = []
    for name in ORDER:
        if name not in reachable:
            continue
        body, _ = transform(sources[name], known)
        body = "\n".join("\t" + line if line.strip() else line for line in body.splitlines())
        modules.append(MODULE_TEMPLATE.format(name=name, body=body))

    graph = {name: sorted(dependencies[name]) for name in ORDER if name in reachable}

    core = (
        COMPAT
        + "local Aurora = (function()\n"
        "\tlocal Modules = {}\n"
        "\tlocal Loaded = {}\n\n"
        "\tlocal function __req(name)\n"
        "\t\tlocal cached = Loaded[name]\n"
        "\t\tif cached ~= nil then\n"
        "\t\t\treturn cached\n"
        "\t\tend\n"
        "\t\tlocal factory = Modules[name]\n"
        "\t\tif not factory then\n"
        "\t\t\terror(\"[Aurora] unknown module: \" .. tostring(name), 0)\n"
        "\t\tend\n"
        "\t\tlocal value = factory()\n"
        "\t\tLoaded[name] = value\n"
        "\t\treturn value\n"
        "\tend\n\n"
        + "\n".join(modules)
        + f'\n\treturn __req("{entry}")\nend)()\n'
    )

    return HEADER.format(version=version) + core, graph


def build_script(path, replacement):
    """Read a runnable script and point its require at the bundled table."""
    with open(path, "r", encoding="utf-8") as handle:
        body = handle.read()
    return re.sub(r'local \w+ = require\([^\n]*\)', replacement, body, count=1)


def main():
    os.makedirs(DIST, exist_ok=True)
    version = source_version()
    core, dependencies = build_core()

    demo = build_script(
        os.path.join(ROOT, "src", "Client", "Main.client.luau"),
        "local UI = Aurora",
    )

    library = core + "\nreturn Aurora\n"
    demo_file = (
        HEADER.format(version=version)
        + "-- Everything below runs on load: paste and execute.\n\n"
        + core
        + "\n" + demo
    )

    preview_core, _ = build_core("Preview")
    preview_file = (
        HEADER.format(version=version)
        + "-- Mounts the live preview of the real components, then stops.\n\n"
        + preview_core
        + "\nlocal AuroraPreview = Aurora\nAuroraPreview.Mount()\n"
    )

    targets = {
        "AuroraUI.luau": library,
        "AuroraDemo.luau": demo_file,
        "AuroraPreview.luau": preview_file,
    }

    for filename, content in targets.items():
        if "script." in content.replace("script.Parent", ""):
            leftover = [
                line for line in content.splitlines()
                if re.search(r"\bscript\b\s*[\.\[]", line)
            ]
            if leftover:
                raise SystemExit(f"[bundle] leftover script reference in {filename}: {leftover[0]}")

        path = os.path.join(DIST, filename)
        with open(path, "w", encoding="utf-8") as handle:
            handle.write(content)
        lines = len(content.splitlines())
        print(f"  {filename:18} {lines:>6} lines  {len(content)/1024:6.1f} KB")

    print("\n  module graph (library entry):")
    for name in ORDER:
        if name not in dependencies:
            continue
        deps = dependencies[name]
        print(f"    {name:14} <- {', '.join(deps) if deps else '(none)'}")


if __name__ == "__main__":
    main()
